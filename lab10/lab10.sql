DROP TABLE IF EXISTS cof_inventory CASCADE;
DROP TABLE IF EXISTS merch_inventory CASCADE;
DROP TABLE IF EXISTS coffees CASCADE;
DROP TABLE IF EXISTS coffee_houses CASCADE;
DROP TABLE IF EXISTS university_students CASCADE;
DROP TABLE IF EXISTS suppliers CASCADE;

CREATE TABLE suppliers (
    sup_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sup_name VARCHAR(255),
    street VARCHAR(255),
    city VARCHAR(255),
    state VARCHAR(255),
    zip VARCHAR(255)
);

CREATE TABLE coffee_houses (
    store_id INTEGER PRIMARY KEY,
    coffee INTEGER,
    merch INTEGER,
    total INTEGER,
    city VARCHAR(255)
);

CREATE TABLE coffees (
    cof_name VARCHAR(32) PRIMARY KEY,
    price REAL,
    sales INTEGER,
    total INTEGER,
    sup_id INTEGER REFERENCES suppliers(sup_id)
);

CREATE TABLE cof_inventory (
    warehouse_id INTEGER,
    cof_name VARCHAR(32) REFERENCES coffees(cof_name),
    quan INTEGER,
    date_val DATE,
    sup_id INTEGER REFERENCES suppliers(sup_id),
    PRIMARY KEY (warehouse_id, cof_name)
);

CREATE TABLE merch_inventory (
    item_id INTEGER PRIMARY KEY,
    item_name VARCHAR(255),
    quan INTEGER,
    date DATE,
    sup_id INTEGER REFERENCES suppliers(sup_id)
);

CREATE TABLE university_students (
    student_id INTEGER PRIMARY KEY,
    first_name TEXT,
    last_name VARCHAR(50),
    email_address VARCHAR(100),
    date_of_birth DATE
);

